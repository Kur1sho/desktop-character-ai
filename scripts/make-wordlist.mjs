// Builds src/shared/spelling/words.ts from SCOWL (via the wordlist-english package).
// Usage: npm pack wordlist-english && tar xzf wordlist-english-*.tgz
//        node scripts/make-wordlist.mjs ./package
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const dir = process.argv[2] ?? './package'
const LEVELS = [10, 20, 35, 40, 50]
const seen = new Set()
const tiers = LEVELS.map((level) => {
  const words = []
  for (const dialect of ['english', 'british', 'american']) {
    for (const w of JSON.parse(readFileSync(join(dir, `${dialect}-words-${level}.json`), 'utf8'))) {
      const word = w.toLowerCase()
      // Plain words only: no possessives, no odd characters.
      if (!/^[a-z]+(?:'[a-z]+)?$/.test(word) || word.endsWith("'s") || seen.has(word)) continue
      seen.add(word)
      words.push(word)
    }
  }
  return words.sort().join(' ')
})
const notice = readFileSync(join(dir, 'Copyright'), 'utf8').split('\n').slice(0, 13).map((l) => `// ${l}`.trimEnd()).join('\n')
writeFileSync(
  'src/shared/spelling/words.ts',
  `// English words for the spelling fixer, most common first (SCOWL size levels ${LEVELS.join(', ')}).
// Generated by scripts/make-wordlist.mjs. Word lists from SCOWL (http://wordlist.aspell.net/):
//
${notice}

export const WORD_TIERS: string[] = ${JSON.stringify(tiers, null, 0).replace(/","/g, '",\n"')}
`
)
